/**
 * Generates src/generated/tool-names.ts from src/generated/tool-names.json.
 *
 * tool-names.json is written by the backend (uv run python scripts/export_tool_names.py)
 * from the tools the MCP servers register. The generated union type makes every
 * callTool name a compile-time check against that registry.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '..', 'src', 'generated');
const names = JSON.parse(fs.readFileSync(path.join(dir, 'tool-names.json'), 'utf8'));

if (!Array.isArray(names) || names.some((n) => typeof n !== 'string' || !/^[a-z0-9_]+$/.test(n))) {
  throw new Error('tool-names.json must be a list of underscore tool names');
}

const out = [
  '// Generated by scripts/gen-tool-names.js from tool-names.json. Do not edit.',
  '// Regenerate: npm run api:types',
  '',
  'export const TOOL_NAMES = [',
  ...names.map((n) => `  ${JSON.stringify(n)},`),
  '] as const;',
  '',
  'export type ToolName = (typeof TOOL_NAMES)[number];',
  '',
].join('\n');

fs.writeFileSync(path.join(dir, 'tool-names.ts'), out);
console.log(`wrote src/generated/tool-names.ts (${names.length} tools)`);
